# countdown script from 10 to 1 
# then print Blast Off at the end using while loop

cnt = 10

while ( cnt > 0 ) :
    print(cnt)
    cnt = cnt - 1     # decreasing count by 1 each time

print("Blast Off!")

# while loop keeps running till cnt becomes 0
# i used short name cnt for counter